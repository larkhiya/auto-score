#!/usr/bin/env node
// Compiles prompts/*.md into src/generated/prompts.js so Code nodes get the exact versioned text (D-014).
// Sections are marked in the markdown with <!-- section: name -->.
//   node scripts/build-prompts.js           (writes)
//   node scripts/build-prompts.js --check   (exits 1 if stale)
const fs = require('node:fs');
const path = require('node:path');
const { ROOT } = require('./lib/env');

const DIR = path.join(ROOT, 'prompts');
const OUT = path.join(ROOT, 'src', 'generated', 'prompts.js');

function parse(md) {
  const sections = {};
  const parts = md.replace(/\r\n/g, '\n').split(/^<!-- section: ([a-z.]+) -->\n/m);
  for (let i = 1; i < parts.length; i += 2) sections[parts[i]] = parts[i + 1].trim();
  return sections;
}

function build() {
  const prompts = {};
  for (const f of fs.readdirSync(DIR).filter((x) => x.endsWith('.md')).sort()) {
    const version = f.replace(/\.md$/, '');
    const sections = parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
    if (!Object.keys(sections).length) throw new Error(`${f} has no <!-- section: ... --> markers`);
    prompts[version] = sections;
  }
  return `// GENERATED by scripts/build-prompts.js from prompts/*.md. Do not edit.\nmodule.exports = ${JSON.stringify(prompts, null, 2)};\n`;
}

if (require.main === module) {
  const code = build();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== code) { console.log('stale: src/generated/prompts.js'); process.exit(1); }
    console.log('prompts up to date');
  } else if (current !== code) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, code);
    console.log('wrote src/generated/prompts.js');
  } else console.log('prompts up to date');
}

module.exports = { build, parse };
